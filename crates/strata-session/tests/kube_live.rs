//! Live Kubernetes exec tests against a real API server.
//!
//! The rest of the engine is covered by unit tests, but none of them can
//! tell you whether the `v4.channel.k8s.io` framing is right, whether the
//! API server accepts the resize message's capitalised field names, or
//! whether it rejects the request for asking for stderr alongside a TTY.
//! Those are exactly the failures that reached users on SSH and VNC only
//! once a real target was in front of them.
//!
//! They are `#[ignore]`d because they need a cluster. To run them:
//!
//! ```text
//! docker compose -f docker-compose.session-test.yml up -d k3s
//! # The first apply of the pod manifest fails: k3s writes it before the
//! # default service account exists. It retries within ~15s, so wait for
//! # the pod to appear rather than for the first apply to succeed.
//! until docker exec strata-kube-target kubectl get pod strata-exec-target \
//!         >/dev/null 2>&1; do sleep 2; done
//! docker exec strata-kube-target \
//!     kubectl wait --for=condition=Ready pod/strata-exec-target --timeout=180s
//! docker run --rm --network strata-session-test-net \
//!     -v "$PWD:/w" -w /w -e CARGO_TARGET_DIR=/tmp/target \
//!     -v strata-session-test_k3s-output:/kube:ro \
//!     -e STRATA_KUBE_TEST_HOST=strata-kube-target \
//!     -e STRATA_KUBE_TEST_CONFIG=/kube/kubeconfig.yaml \
//!     rust:1.99-slim-trixie \
//!     cargo test -p strata-session --all-features --test kube_live -- --ignored
//! docker compose -f docker-compose.session-test.yml down -v
//! ```

#![cfg(feature = "kubernetes")]

use std::sync::Arc;
use std::time::Duration;

use base64::prelude::*;
use bytes::Bytes;
use secrecy::SecretString;
use strata_session::engine::kube::{KubeConfig, KubeEngine};
use strata_session::engine::{InputEvent, Protocol, ProtocolEngine, TargetEvent, TargetSpec};

/// Long enough to absorb a cold container, short enough that a hang is a
/// test failure rather than a hung CI job.
const IO_TIMEOUT: Duration = Duration::from_secs(30);

/// Pod created by `tests/k3s/exec-target.yaml`.
const POD: &str = "strata-exec-target";

fn required(name: &str) -> String {
    std::env::var(name).unwrap_or_else(|_| {
        panic!(
            "{name} is not set - these tests need a live API server; see the \
             module header for the docker compose invocation"
        )
    })
}

/// Pull one base64 field out of a kubeconfig.
///
/// Hand-rolled rather than pulling in a YAML parser for a test: the file
/// is generated by k3s, so its shape is fixed, and a wrong answer here
/// fails loudly at the TLS handshake rather than silently.
fn kubeconfig_field(kubeconfig: &str, field: &str) -> String {
    let needle = format!("{field}:");
    let encoded = kubeconfig
        .lines()
        .find_map(|line| line.trim().strip_prefix(&needle))
        .unwrap_or_else(|| panic!("kubeconfig has no `{field}`"))
        .trim();
    let decoded = BASE64_STANDARD
        .decode(encoded)
        .unwrap_or_else(|e| panic!("`{field}` is not base64: {e}"));
    String::from_utf8(decoded).unwrap_or_else(|e| panic!("`{field}` is not text: {e}"))
}

fn config() -> KubeConfig {
    let kubeconfig = std::fs::read_to_string(required("STRATA_KUBE_TEST_CONFIG"))
        .expect("reading the kubeconfig k3s wrote");
    KubeConfig {
        pod: POD.to_owned(),
        ca_cert: Some(kubeconfig_field(&kubeconfig, "certificate-authority-data")),
        client_cert: Some(kubeconfig_field(&kubeconfig, "client-certificate-data")),
        client_key: Some(SecretString::from(kubeconfig_field(
            &kubeconfig,
            "client-key-data",
        ))),
        ..KubeConfig::default()
    }
}

fn spec() -> TargetSpec {
    TargetSpec {
        connect_addr: None,
        protocol: Protocol::KubeExec,
        hostname: required("STRATA_KUBE_TEST_HOST"),
        port: std::env::var("STRATA_KUBE_TEST_PORT")
            .ok()
            .and_then(|p| p.parse().ok())
            .unwrap_or(6443),
        username: String::new(),
        secret: SecretString::from(String::new()),
        width: 640,
        height: 384,
    }
}

async fn connect_with(config: KubeConfig) -> KubeEngine {
    KubeEngine::connect(spec(), Arc::new(config))
        .await
        .expect("opening an exec session")
}

async fn connect() -> KubeEngine {
    connect_with(config()).await
}

/// Read until `needle` appears, or fail.
async fn read_until(engine: &mut KubeEngine, needle: &str) -> String {
    let mut seen = String::new();
    let deadline = tokio::time::Instant::now() + IO_TIMEOUT;
    loop {
        let event = tokio::time::timeout_at(deadline, engine.next_event())
            .await
            .unwrap_or_else(|_| panic!("timed out waiting for {needle:?}; saw {seen:?}"))
            .expect("engine error");
        match event {
            Some(TargetEvent::TerminalOutput(bytes)) => {
                seen.push_str(&String::from_utf8_lossy(&bytes));
                if seen.contains(needle) {
                    return seen;
                }
            }
            Some(TargetEvent::Disconnected { reason, .. }) => {
                panic!("session ended waiting for {needle:?}: {reason}; saw {seen:?}")
            }
            Some(_) => {}
            None => panic!("stream ended waiting for {needle:?}; saw {seen:?}"),
        }
    }
}

async fn type_line(engine: &mut KubeEngine, line: &str) {
    engine
        .handle_input(InputEvent::Text(Bytes::from(format!("{line}\n"))))
        .await
        .expect("writing to the pod");
}

#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn a_pod_gives_us_a_shell() {
    let mut engine = connect().await;
    // Split so the shell's own echo of the command cannot satisfy the
    // assertion; only the command's output contains the joined string.
    type_line(&mut engine, "echo SHELL''_READY").await;
    read_until(&mut engine, "SHELL_READY").await;
}

/// The framing byte must be stripped. Left on, it appears as a stray
/// control character at the head of every chunk.
#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn output_carries_no_channel_prefix() {
    let mut engine = connect().await;
    type_line(&mut engine, "printf 'MARK''ER\\n'").await;
    let seen = read_until(&mut engine, "MARKER").await;
    let line = seen
        .lines()
        .find(|l| l.trim() == "MARKER")
        .unwrap_or_else(|| panic!("no clean MARKER line in {seen:?}"));
    assert_eq!(line.trim(), "MARKER", "channel byte leaked into {line:?}");
}

/// The resize message uses capitalised field names, and the API server
/// ignores it silently if they are wrong -- so this asserts on what the
/// pod believes its window is, not on the send succeeding.
#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn the_pty_takes_a_new_size() {
    let mut engine = connect().await;
    type_line(&mut engine, "echo READ''Y").await;
    read_until(&mut engine, "READY").await;

    // 100x40 cells at the engine's default 8x16 cell.
    engine
        .handle_input(InputEvent::Resize {
            width: 800,
            height: 640,
            dpi: None,
        })
        .await
        .expect("resizing");

    // The kubelet applies resizes asynchronously to stdin, so a `stty size`
    // sent straight after can still report the old window. Wait in the pod
    // for the new size instead.
    type_line(
        &mut engine,
        "until [ \"$(stty size)\" = '40 100' ]; do sleep 0.2; done; echo RESIZE''D",
    )
    .await;
    read_until(&mut engine, "RESIZED").await;
}

#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn leaving_the_shell_ends_the_session() {
    let mut engine = connect().await;
    type_line(&mut engine, "echo READ''Y").await;
    read_until(&mut engine, "READY").await;
    type_line(&mut engine, "exit").await;

    let deadline = tokio::time::Instant::now() + IO_TIMEOUT;
    loop {
        let event = tokio::time::timeout_at(deadline, engine.next_event())
            .await
            .expect("timed out waiting for the session to end")
            .expect("engine error");
        match event {
            Some(TargetEvent::Disconnected { .. }) | None => return,
            Some(_) => {}
        }
    }
}

/// The API server reports this on the error stream rather than by
/// refusing the WebSocket, so a naive client connects and then hangs.
#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn a_pod_that_does_not_exist_is_reported() {
    let mut config = config();
    config.pod = "strata-no-such-pod".to_owned();

    // Either the upgrade fails or the error stream explains why; both are
    // acceptable, silence is not.
    let Ok(mut engine) = KubeEngine::connect(spec(), Arc::new(config)).await else {
        return;
    };
    let deadline = tokio::time::Instant::now() + IO_TIMEOUT;
    loop {
        let event = tokio::time::timeout_at(deadline, engine.next_event())
            .await
            .expect("timed out; the engine neither connected nor complained")
            .expect("engine error");
        match event {
            Some(TargetEvent::Disconnected { reason, .. }) => {
                assert!(
                    reason.contains("strata-no-such-pod") || reason.contains("not found"),
                    "unhelpful reason: {reason}"
                );
                return;
            }
            Some(_) => {}
            None => return,
        }
    }
}

#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn a_configured_command_runs_instead_of_a_shell() {
    let mut config = config();
    config.command = vec!["/bin/sh".to_owned(), "-c".to_owned(), "id -u".to_owned()];
    let mut engine = connect_with(config).await;
    // busybox images run as root, so the command's own output is `0`.
    read_until(&mut engine, "0").await;
}

/// A read-only session must reach the pod but carry nothing into it.
#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn a_read_only_session_types_nothing() {
    let mut config = config();
    config.read_only = true;
    let mut engine = connect_with(config).await;

    type_line(&mut engine, "echo SHOULD''_NOT_APPEAR").await;

    let deadline = tokio::time::Instant::now() + Duration::from_secs(5);
    let mut seen = String::new();
    while let Ok(Ok(Some(event))) = tokio::time::timeout_at(deadline, engine.next_event()).await {
        if let TargetEvent::TerminalOutput(bytes) = event {
            seen.push_str(&String::from_utf8_lossy(&bytes));
        }
    }
    assert!(
        !seen.contains("SHOULD_NOT_APPEAR"),
        "read-only session reached the pod: {seen:?}"
    );
}

/// Requesting stderr alongside a TTY makes the API server reject the
/// request outright, which would show as a failure to connect at all.
#[tokio::test]
#[ignore = "needs a live Kubernetes API server"]
async fn a_tty_session_is_accepted() {
    let engine = connect().await;
    assert_eq!(engine.protocol(), Protocol::KubeExec);
}
